export function filterMapSpots(options: {
  groupId?: GroupId | 'all';
  category?: SpotCategory | 'all';
  query?: string;
  savedIds?: string[];
  onlySaved?: boolean;
}): MapSpot[] {
  const { groupId = 'all', category = 'all', query = '', savedIds = [], onlySaved = false } = options;
  const q = query.trim().toLowerCase();

  return MAP_SPOTS.filter((spot) => {
    if (groupId !== 'all' && !spot.groupIds.includes(groupId)) return false;
    if (category !== 'all' && spot.category !== category) return false;
    if (onlySaved && !savedIds.includes(spot.id)) return false;
    if (q) {
      const searchable = [
        spot.name.en,
        spot.name.ko,
        spot.name.es ?? '',
        spot.district.en,
        spot.district.ko,
        spot.story.en,
        spot.story.ko,
        ...spot.memberNames,
      ]
        .join(' ')
        .toLowerCase();
      if (!searchable.includes(q)) return false;
    }
    return true;
  });
}
